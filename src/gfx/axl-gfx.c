// ===================================================================
// Text rendering
// ===================================================================

int
axl_gfx_draw_text(
    uint32_t     x,
    uint32_t     y,
    const char  *text,
    AxlGfxPixel  color,
    uint32_t     scale
    )
{
    EFI_GRAPHICS_OUTPUT_PROTOCOL *g = gop_get();
    EFI_GRAPHICS_OUTPUT_BLT_PIXEL fg;
    EFI_GRAPHICS_OUTPUT_BLT_PIXEL *buf;
    size_t     len;
    uint32_t   char_w;
    uint32_t   char_h;
    uint32_t   total_w;
    uint32_t   total_h;
    size_t     ci;

    if (g == NULL || text == NULL || scale == 0) {
        return AXL_ERR;
    }

    len = axl_strlen(text);
    if (len == 0) {
        return AXL_OK;
    }

    char_w  = FONT_W * scale;
    char_h  = FONT_H * scale;
    total_w = (uint32_t)len * char_w;
    total_h = char_h;

    fg.Blue     = color.blue;
    fg.Green    = color.green;
    fg.Red      = color.red;
    fg.Reserved = 0;

    /* Clamp to screen bounds */
    {
        AxlGfxInfo scr;
        if (axl_gfx_get_info(&scr) == AXL_OK) {
            if (x >= scr.width || y >= scr.height) {
                return AXL_ERR;
            }
            if (x + total_w > scr.width) {
                total_w = scr.width - x;
            }
            if (y + total_h > scr.height) {
                total_h = scr.height - y;
            }
        }
    }

    buf = axl_malloc((size_t)total_w * total_h * sizeof(*buf));
    if (buf == NULL) {
        return AXL_ERR;
    }

    /* Capture existing screen content as background */
    EFI_STATUS status = g->Blt(
        g, buf, EfiBltVideoToBltBuffer,
        x, y, 0, 0, total_w, total_h,
        total_w * sizeof(*buf)
        );
    if (status != 0) {
        /* No existing content — zero-fill */
        size_t npixels = (size_t)total_w * total_h;
        size_t pi;
        for (pi = 0; pi < npixels; pi++) {
            buf[pi].Blue = 0;
            buf[pi].Green = 0;
            buf[pi].Red = 0;
            buf[pi].Reserved = 0;
        }
    }

    /* Render each character into the buffer */
    for (ci = 0; ci < len; ci++) {
        unsigned char ch = (unsigned char)text[ci];
        uint32_t      glyph_idx;
        uint32_t      row;
        uint32_t      col;
        uint32_t      ox = (uint32_t)ci * char_w;

        if (ch < 0x20 || ch > 0x7E) {
            continue;  /* skip non-printable (background preserved) */
        }
        glyph_idx = ch - 0x20;

        for (row = 0; row < FONT_H; row++) {
            uint8_t bits = font_8x16[glyph_idx * FONT_H + row];
            for (col = 0; col < FONT_W; col++) {
                if (bits & (0x80 >> col)) {
                    uint32_t sy, sx;
                    for (sy = 0; sy < scale; sy++) {
                        for (sx = 0; sx < scale; sx++) {
                            uint32_t px = ox + col * scale + sx;
                            uint32_t py = row * scale + sy;
                            buf[py * total_w + px] = fg;
                        }
                    }
                }
            }
        }
    }

    /* Blit the composited buffer to screen */
    status = g->Blt(
        g, buf, EfiBltBufferToVideo,
        0, 0, x, y, total_w, total_h,
        total_w * sizeof(*buf)
        );

    axl_free(buf);
    return (status == 0) ? AXL_OK : AXL_ERR;
}
